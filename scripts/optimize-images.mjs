// Re-encodes everything in public/images and writes size + a dominant-colour placeholder
// to src/data/image-meta.ts (kept tiny because client components bundle it).
import sharp from "sharp";
import { readdir, writeFile, readFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";

const root = join(process.cwd(), "public", "images");
const out = join(process.cwd(), "src", "data", "image-meta.ts");

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)])),
  );
  return files.flat().filter((f) => /\.(jpe?g|png|webp)$/i.test(f));
}

const hex = (n) => n.toString(16).padStart(2, "0");

const meta = {};
for (const file of (await walk(root)).sort()) {
  const input = await readFile(file);
  const { width, height } = await sharp(input).metadata();
  if (/\.jpe?g$/i.test(file)) {
    const buf = await sharp(input).jpeg({ quality: 80, mozjpeg: true, progressive: true }).toBuffer();
    // Only rewrite on a meaningful saving so repeated runs don't degrade quality.
    if (buf.length < input.length * 0.9) await writeFile(file, buf);
  }
  const { dominant } = await sharp(input).resize(24).stats();
  const key = "/images/" + relative(root, file).split(sep).join("/");
  meta[key] = [width, height, `#${hex(dominant.r)}${hex(dominant.g)}${hex(dominant.b)}`];
}

await writeFile(
  out,
  `// Generated by scripts/optimize-images.mjs — do not edit by hand.\n` +
    `export type ImageMeta = [width: number, height: number, color: string];\n\n` +
    `export const imageMeta: Record<string, ImageMeta> = ${JSON.stringify(meta)};\n`,
);
console.log(`Processed ${Object.keys(meta).length} images`);
