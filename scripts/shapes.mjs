// Generates morphable clip-path polygons (same point count for every shape)
// into src/app/shapes.css. Run with `npm run shapes`.
import { writeFile } from "node:fs/promises";
import { join } from "node:path";

const N = 150;
const TAU = Math.PI * 2;
const mod = (a, n) => ((a % n) + n) % n;

// Each shape is a polar radius function r(θ) in a unit box (0.5 = edge).
const leaf = (L, W, axis) => {
  const rho = (L * L + W * W) / (2 * W);
  return (t) => {
    const phi = t - axis;
    const s = Math.abs(Math.sin(phi));
    const k = rho - W;
    return -s * k + Math.sqrt(s * s * k * k - k * k + rho * rho);
  };
};

const shapes = {
  circle: () => 0.5,
  sun: (t) => 0.4 + 0.1 * Math.pow(Math.abs(Math.cos(6 * t)), 0.45),
  cookie: (t) => 0.455 + 0.045 * Math.cos(8 * t),
  flower: (t) => 0.32 + 0.18 * Math.abs(Math.cos(3 * t)),
  clover: (t) => 0.3 + 0.2 * Math.pow(Math.abs(Math.cos(2 * t)), 0.55),
  seal: (t) => 0.445 + 0.055 * (1 - 2 * Math.abs(mod((15 * t) / Math.PI, 2) - 1)),
  blob: (t) => 0.43 + 0.045 * Math.sin(2 * t + 0.6) + 0.03 * Math.cos(3 * t + 1.3) + 0.02 * Math.sin(5 * t + 2.1),
  squircle: (t) => 0.5 / Math.pow(Math.pow(Math.abs(Math.cos(t)), 4) + Math.pow(Math.abs(Math.sin(t)), 4), 0.25),
  leaf: leaf(0.66, 0.3, -Math.PI / 4),
  "leaf-alt": leaf(0.66, 0.3, Math.PI / 4),
};

const fmt = (n) => (Math.round(n * 10) / 10).toString();

function polygon(fn) {
  const pts = [];
  let max = 0;
  const raw = [];
  for (let i = 0; i < N; i++) {
    const t = -Math.PI / 2 + (i / N) * TAU;
    const r = fn(t);
    raw.push([t, r]);
    max = Math.max(max, Math.abs(r * Math.cos(t)), Math.abs(r * Math.sin(t)));
  }
  const scale = max > 0.5 ? 0.5 / max : 1;
  for (const [t, r] of raw) {
    pts.push(`${fmt(50 + 100 * r * scale * Math.cos(t))}% ${fmt(50 + 100 * r * scale * Math.sin(t))}%`);
  }
  return `polygon(${pts.join(",")})`;
}

const vars = Object.entries(shapes).map(([name, fn]) => `  --shape-${name}: ${polygon(fn)};`);
const classes = Object.keys(shapes).map((name) => `  .shape-${name} {\n    clip-path: var(--shape-${name});\n  }`);

const css = `/* Generated by scripts/shapes.mjs — do not edit by hand. */
:root {
${vars.join("\n")}
}

/* Layered so Tailwind utilities (e.g. hover morphs) can override them. */
@layer components {
${classes.join("\n")}
}
`;

await writeFile(join(process.cwd(), "src/app/shapes.css"), css);
console.log(`Wrote ${Object.keys(shapes).length} shapes (${css.length} bytes)`);
